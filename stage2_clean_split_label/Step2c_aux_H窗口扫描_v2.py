# ============================================================
# 文件名：Step2c_aux_H窗口扫描_v2.py  (v2 修订：train/val only, read labeled outputs)
# 作用：
#   直接读取 Step2c 生成的 labeled 表，对不同 H 的 train/val 统计：
#     - valid_rows / pos_count / pos_rate
#   不输出 test，避免任何 test-set 相关信息进入“设定证据链”
#
# 输入：
#   01_interim/step2c_machine_slice_labeled_FAILonly_H{H}h_v2.csv
# 输出：
#   05_reports/step2c_horizon_scan.csv
#   05_reports/step2c_horizon_scan.txt
# ============================================================

import os
import numpy as np
import pandas as pd

ROOT_DIR = r"D:\pycharmcode\GCT数据集-v2处理"
INTERIM_DIR = os.path.join(ROOT_DIR, "01_interim")
REPORT_DIR = os.path.join(ROOT_DIR, "05_reports")
os.makedirs(REPORT_DIR, exist_ok=True)

HOURS_LIST = [4, 6, 8, 12]

OUT_CSV = os.path.join(REPORT_DIR, "step2c_horizon_scan.csv")
OUT_TXT = os.path.join(REPORT_DIR, "step2c_horizon_scan.txt")

MID = "machine_id"
SPLIT = "split"

def split_stats_from_labeled(df, label_col, split_name):
    sub = df[df[SPLIT] == split_name]
    sub_valid = sub[sub[label_col].notna()]
    if len(sub) == 0:
        return dict(valid_rows=0, pos_count=0, pos_rate=np.nan)
    if len(sub_valid) == 0:
        return dict(valid_rows=0, pos_count=0, pos_rate=0.0)

    y = pd.to_numeric(sub_valid[label_col], errors="coerce")
    # label should be 0/1
    pos_count = int((y == 1).sum())
    return dict(
        valid_rows=int(len(sub_valid)),
        pos_count=pos_count,
        pos_rate=float(pos_count / len(sub_valid))
    )

print("=" * 90)
print("Step2c_aux(v2 修订)：Horizon scan (train/val only) — read Step2c labeled outputs")
print("=" * 90)

rows = []
lines = []
lines.append("=== Step2c_aux(v2) Horizon Scan (train/val only; test excluded) ===")
lines.append("This report is generated by reading Step2c labeled outputs to ensure identical label domain.")
lines.append("")

for H in HOURS_LIST:
    label_col = f"label_fail_H{H}h"
    in_csv = os.path.join(INTERIM_DIR, f"step2c_machine_slice_labeled_FAILonly_H{H}h_v2.csv")
    assert os.path.exists(in_csv), f"❌ missing labeled file: {in_csv}"

    usecols = [MID, SPLIT, label_col]
    df = pd.read_csv(in_csv, usecols=usecols, low_memory=False)

    # 类型规整
    df[MID] = pd.to_numeric(df[MID], errors="coerce").astype("int64")
    df[SPLIT] = df[SPLIT].astype(str)

    st_train = split_stats_from_labeled(df, label_col, "train")
    st_val   = split_stats_from_labeled(df, label_col, "val")

    rows.append({
        "H_hours": H,
        "train_valid_rows": st_train["valid_rows"],
        "train_pos_count": st_train["pos_count"],
        "train_pos_rate": st_train["pos_rate"],
        "val_valid_rows": st_val["valid_rows"],
        "val_pos_count": st_val["pos_count"],
        "val_pos_rate": st_val["pos_rate"],
        "source_labeled_csv": in_csv
    })

    lines.append(f"[H={H}h] train(valid={st_train['valid_rows']}, pos={st_train['pos_count']}, rate={st_train['pos_rate']:.6f}) "
                 f"val(valid={st_val['valid_rows']}, pos={st_val['pos_count']}, rate={st_val['pos_rate']:.6f})")

out = pd.DataFrame(rows).sort_values("H_hours")
out.to_csv(OUT_CSV, index=False, encoding="utf-8-sig")

with open(OUT_TXT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
    f.write("\n\n")
    f.write("NOTE: Test split is intentionally excluded to avoid any test-set leakage into horizon selection.\n")

print("[输出]", OUT_CSV)
print("[输出]", OUT_TXT)
print("\n[预览]")
print(out.to_string(index=False))
print("=" * 90)